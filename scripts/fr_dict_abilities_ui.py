def translate_ability_or_ui(key: str, en_str: str) -> str:
    """
    Returns the fluent French translation for any key in ActiveAbilities,
    PassiveAbilities, HeroSpecializations, RankModifiers, HeroClasses,
    Crossroads, Heroes, Guilds, or UI.
    """
    if key in FR_ABILITIES_UI:
        return FR_ABILITIES_UI[key]
    if not en_str:
        return en_str

    # Check if exact English text matches any entry in FR_ABILITIES_UI
    for k_existing, fr_val in FR_ABILITIES_UI.items():
        if en_str == k_existing:
            return fr_val

    # Protect `[inner]<tag>` blocks and `{...}` placeholders
    saved_tags = []

    def _save_tag(m):
        inner, tag = m.group(1), m.group(2)
        tr_inner = _translate_tag_inner(inner, tag)
        idx = len(saved_tags)
        saved_tags.append(f"[{tr_inner}]<{tag}>")
        return f"__TAG_{idx}__"

    s = re.sub(r"\[([^\[\]]*)\]<([a-zA-Z_0-9/_-]+)>", _save_tag, en_str)

    saved_braces = []

    def _save_brace(m):
        idx = len(saved_braces)
        saved_braces.append(m.group(0))
        return f"__BRACE_{idx}__"

    s = re.sub(r"\{[^{}]*\}", _save_brace, s)

    # Fallback phrase replacements
    replacements = [
        ("At the start of combat,", "Au début du combat,"),
        ("At start of combat,", "Au début du combat,"),
        ("Whenever", "Chaque fois que"),
        ("permanently gain", "gagne définitivement"),
        ("permanently gains", "gagne définitivement"),
        ("this game", "au cours de cette partie"),
        ("this combat", "au cours de ce combat"),
        ("each combat", "à chaque combat"),
        ("per equipped item", "par objet équipé"),
        ("Gain an item slot.", "Gagne un emplacement d'objet."),
        ("Gain the", "Gagne la classe"),
        ("class and", "et"),
        ("Active Ability", "Compétence Active"),
        ("Passive Ability", "Compétence Passive"),
        ("adjacent enemies", "ennemis adjacents"),
        ("all enemies", "tous les ennemis"),
        ("auto attacks", "attaques auto"),
        ("auto attack", "attaque auto"),
        ("seconds", "secondes"),
        ("second", "seconde"),
        ("damage", "dégâts"),
        ("enemies", "ennemis"),
        ("enemy", "ennemi"),
        ("Heroes", "Héros"),
        ("Hero", "Héros"),
    ]
    for en_p, fr_p in replacements:
        s = s.replace(en_p, fr_p)

    for idx, br in enumerate(saved_braces):
        s = s.replace(f"__BRACE_{idx}__", br)
    for idx, tg in enumerate(saved_tags):
        s = s.replace(f"__TAG_{idx}__", tg)

    return s
